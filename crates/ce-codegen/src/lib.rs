//! CEngine client generator (draft v1): a typed Python client from a template manifest.
//!
//! The output is one self-contained `.py` file that needs only the standard library and
//! Python 3.11 or newer. Decimal fields are `Decimal` (never `float`), dates are `date`,
//! datetimes are timezone-aware, and filters and sorts are built from the entity's declared
//! fields: `Item.f.unit_cost > Decimal("2")`.

use ce_manifest::Manifest;
use serde_json::Value;
use std::fmt::Write;

const RUNTIME: &str = include_str!("python_runtime.py");

const KEYWORDS: &[&str] = &[
    "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue",
    "def", "del", "elif", "else", "except", "finally", "for", "from", "global", "if", "import",
    "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return", "try", "while",
    "with", "yield", "match", "case", "type", "id", "version", "f",
];

/// A Python identifier for a manifest name (names are `[a-z][a-z0-9_]*`, so only keywords and
/// the few names the generated classes use themselves need a suffix).
fn ident(name: &str) -> String {
    if KEYWORDS.contains(&name) {
        format!("{name}_")
    } else {
        name.to_string()
    }
}

/// `inventory_item` becomes `InventoryItem`.
fn class_name(name: &str) -> String {
    let mut out = String::new();
    for part in name.split('_').filter(|p| !p.is_empty()) {
        let mut cs = part.chars();
        if let Some(c) = cs.next() {
            out.extend(c.to_uppercase());
            out.push_str(cs.as_str());
        }
    }
    if out.chars().next().is_none_or(|c| c.is_ascii_digit()) {
        out.insert(0, 'E');
    }
    out
}

fn py_type(f: &Value) -> String {
    match f["type"].as_str().unwrap_or("") {
        "string" | "text" | "ref" => "str".into(),
        "integer" => "int".into(),
        "decimal" => "Decimal".into(),
        "boolean" => "bool".into(),
        "date" => "date".into(),
        "datetime" => "datetime".into(),
        "enum" => {
            let vals: Vec<String> = f["values"]
                .as_array()
                .into_iter()
                .flatten()
                .filter_map(Value::as_str)
                .map(|v| format!("{v:?}"))
                .collect();
            format!("Literal[{}]", vals.join(", "))
        }
        _ => "Any".into(),
    }
}

/// The Python source of a client for `m`.
pub fn python(m: &Manifest) -> String {
    let title = m.value["template"]["title"]
        .as_str()
        .or_else(|| m.value["template"]["name"].as_str())
        .unwrap_or("template");
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# Generated by ce-codegen from the \"{title}\" manifest (hash {}). Do not edit.",
        m.hash
    );
    out.push_str(RUNTIME);
    out.push('\n');

    let entities = m.value["entities"].as_object().cloned().unwrap_or_default();
    for (name, ent) in &entities {
        let class = class_name(name);
        let fields = ent["fields"].as_object().cloned().unwrap_or_default();
        let _ = writeln!(out, "\n\nclass {class}Fields:");
        let _ = writeln!(
            out,
            "    \"\"\"Filter and sort handles for the fields of {name}.\"\"\""
        );
        let _ = writeln!(out, "    id = Field(\"id\")");
        for fname in fields.keys() {
            let _ = writeln!(out, "    {} = Field({fname:?})", ident(fname));
        }
        let _ = writeln!(out, "\n\n@dataclass");
        let _ = writeln!(out, "class {class}(Model):");
        let _ = writeln!(out, "    \"\"\"A record of the {name} entity.\"\"\"");
        let _ = writeln!(out, "    id: str = \"\"");
        let _ = writeln!(out, "    version: int = 0");
        for (fname, f) in &fields {
            let _ = writeln!(out, "    {}: Optional[{}] = None", ident(fname), py_type(f));
        }
        let _ = writeln!(out, "    _entity: ClassVar[str] = {name:?}");
        let _ = writeln!(out, "    f: ClassVar[{class}Fields] = {class}Fields()");
        let _ = writeln!(
            out,
            "    _columns: ClassVar[dict[str, tuple[str, bool]]] = {{"
        );
        for (fname, f) in &fields {
            let ty = f["type"].as_str().unwrap_or("");
            let ro = f["computed"].is_string();
            let _ = writeln!(
                out,
                "        {fname:?}: ({ty:?}, {}),",
                if ro { "True" } else { "False" }
            );
        }
        let _ = writeln!(out, "    }}");
        let _ = writeln!(out, "    _pyname: ClassVar[dict[str, str]] = {{");
        for fname in fields.keys() {
            let _ = writeln!(out, "        {fname:?}: {:?},", ident(fname));
        }
        let _ = writeln!(out, "    }}");
    }

    let _ = writeln!(out, "\n\nclass Client:");
    let _ = writeln!(
        out,
        "    \"\"\"Talks to one installation: `Client(\"https://host\", \"my-installation\", token)`.\n"
    );
    let _ = writeln!(
        out,
        "    Each entity is an attribute with list, iter, get, create, update and delete."
    );
    let _ = writeln!(out, "    \"\"\"\n");
    for name in entities.keys() {
        let _ = writeln!(out, "    {}: Resource[{}]", ident(name), class_name(name));
    }
    let _ = writeln!(
        out,
        "\n    def __init__(self, base_url: str, installation: str, token: str, *, timeout: float = 30.0):"
    );
    let _ = writeln!(out, "        http = _Http(base_url, token, timeout)");
    let _ = writeln!(out, "        self._http = http");
    for name in entities.keys() {
        let _ = writeln!(
            out,
            "        self.{} = Resource(http, installation, {})",
            ident(name),
            class_name(name)
        );
    }
    if entities.is_empty() {
        let _ = writeln!(out, "        pass");
    }
    out
}
